for (const [locale, files] of Object.entries(translations)) {
  const localeDir = path.join(localesDir, locale);
  if (!fs.existsSync(localeDir)) {
    fs.mkdirSync(localeDir, { recursive: true });
  }

  for (const [filename, content] of Object.entries(files)) {
    const filePath = path.join(localeDir, filename);
    fs.writeFileSync(filePath, JSON.stringify(content, null, 2) + '\n', 'utf8');
    console.log(`✅ Written: ${locale}/${filename}`);
  }
}

// For remaining locales (ur, gu, kn, or, ml, pa, as, es), copy English files
// so they have valid structure (i18next will use them with fallbackLng: 'en')
const enDir = path.join(localesDir, 'en');
const enFiles = fs.readdirSync(enDir).filter(f => f.endsWith('.json'));
const remainingLocales = ['ur', 'gu', 'kn', 'or', 'ml', 'pa', 'as', 'es'];

for (const locale of remainingLocales) {
  const localeDir = path.join(localesDir, locale);
  if (!fs.existsSync(localeDir)) {
    fs.mkdirSync(localeDir, { recursive: true });
  }
  for (const file of enFiles) {
    const src = path.join(enDir, file);
    const dest = path.join(localeDir, file);
    fs.copyFileSync(src, dest);
  }
  console.log(`📋 Copied English fallback files to ${locale}/`);
}

